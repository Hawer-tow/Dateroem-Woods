// The site didn't set any real HTTP cookies before this - auth uses
// localStorage, and the cart was pure in-memory (lost on every reload).
// Tiny helpers so CartContext (and any future analytics/marketing script)
// have a real place to read/write, gated by CookieConsentContext rather
// than writing directly.
export function setCookie(name, value, days = 365) {
  const expires = new Date(Date.now() + days * 24 * 60 * 60 * 1000).toUTCString()
  document.cookie = `${name}=${encodeURIComponent(value)}; expires=${expires}; path=/; SameSite=Lax`
}

export function getCookie(name) {
  const match = document.cookie.match(new RegExp(`(?:^|; )${name}=([^;]*)`))
  return match ? decodeURIComponent(match[1]) : null
}

export function deleteCookie(name) {
  document.cookie = `${name}=; expires=Thu, 01 Jan 1970 00:00:00 UTC; path=/; SameSite=Lax`
}
